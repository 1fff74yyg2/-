    @Override
    public void setRotationAngles(float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch, float scaleFactor, Entity entityIn) {
        super.setRotationAngles(limbSwing, limbSwingAmount, ageInTicks, netHeadYaw, headPitch, scaleFactor, entityIn);
        resetToDefaultPose();
        LivingEntity living = (LivingEntity) entityIn;

        if(living.isInWater()) {
            float speed = ageInTicks * 0.12F;
            float amp = 0.08F;
            this.Tail1.rotateAngleY = Mth.sin(speed) * amp;
            this.Tail2.rotateAngleY = Mth.sin(speed - 0.3F) * amp * 1.25F;
            this.Tail3.rotateAngleY = Mth.sin(speed - 0.6F) * amp * 1.5F;
            this.Tail4.rotateAngleY = Mth.sin(speed - 0.9F) * amp * 1.75F;
            this.Tail5.rotateAngleY = Mth.sin(speed - 1.2F) * amp * 2.0F;
            this.Tail6.rotateAngleY = Mth.sin(speed - 1.5F) * amp * 2.25F;
            this.Tail7.rotateAngleY = Mth.sin(speed - 1.8F) * amp * 2.5F;
            this.Tail8.rotateAngleY = Mth.sin(speed - 2.1F) * amp * 2.75F;
            this.Tail9.rotateAngleY = Mth.sin(speed - 2.4F) * amp * 3.0F;
            this.Tail10.rotateAngleY = Mth.sin(speed - 2.7F) * amp * 3.25F;
        }

        this.Neck1.rotateAngleY = netHeadYaw * 0.25F * 0.017453292F;
    }

